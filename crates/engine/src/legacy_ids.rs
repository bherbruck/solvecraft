/// The current id for a command id that may be a legacy one (unchanged otherwise).
pub fn current_id(id: &str) -> &str {
    LEGACY_IDS.iter().find(|(old, _)| old.eq_ignore_ascii_case(id)).map(|(_, new)| *new).unwrap_or(id)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_legacy_id_names_a_command() {
        let unknown: Vec<&str> =
            LEGACY_IDS.iter().filter(|(_, new)| crate::find_command(new).is_none_or(|c| c.id != *new)).map(|(_, new)| *new).collect();
        // The construction set and Split Face are on a branch not yet merged when the table was made.
        let pending = ["solid.split_face"];
        let unknown: Vec<&str> = unknown
            .into_iter()
            .filter(|n| {
                !pending.contains(n)
                    && !n.starts_with("construct.axis")
                    && !n.starts_with("construct.point")
                    && ![
                        "construct.plane.midplane",
                        "construct.plane.two_edges",
                        "construct.plane.three_points",
                        "construct.plane.tangent",
                        "construct.plane.along_path",
                    ]
                    .contains(n)
            })
            .collect();
        assert!(unknown.is_empty(), "{unknown:?}");
        assert_eq!(crate::find_command("SketchCreate").map(|c| c.id), Some("sketch.create"));
    }
}
